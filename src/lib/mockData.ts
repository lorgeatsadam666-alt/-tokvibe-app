/**
 * Guarantees that every page reload or feed refresh surfaces a DIFFERENT video first
 * and shuffles the remaining feed so the user always discovers fresh content.
 */
export function getFreshFeedVideos(
  sourceVideos: VideoItem[] = INITIAL_VIDEOS,
  currentFirstId?: string
): VideoItem[] {
  if (sourceVideos.length <= 1) return [...sourceVideos];

  // Guarantee that every video in the feed belongs to a strictly unique creator (one video per user)
  const uniqueAuthorMap = new Map<string, VideoItem>();
  sourceVideos.forEach((v) => {
    if (!uniqueAuthorMap.has(v.authorId)) {
      uniqueAuthorMap.set(v.authorId, v);
    }
  });

  const uniqueVideos = Array.from(uniqueAuthorMap.values());
  for (let i = uniqueVideos.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [uniqueVideos[i], uniqueVideos[j]] = [uniqueVideos[j], uniqueVideos[i]];
  }

  return uniqueVideos;
}


